"""
StaLLM — validation report for the span-level SonarQube oracle (RQ1/RQ2)
=========================================================================
Compares file-name matching (preliminary ENASE pipeline) with path matching
(current pipeline) on the archive evaluated in RQ1/RQ2, checks line ranges and
duplicates, and prints a sample of matched records next to the source line
they point to, for manual inspection.

Usage:
    python validate_oracle.py            # writes output/paper_results/stats/oracle_validation.md
"""

from __future__ import annotations

import collections
import random
import zipfile
from pathlib import Path

from StaLLM_core import (_align_gt_to_zip, _build_universe, _read_csv_robust, _zip_listing,
                         load_ground_truth_spans)

ZIP = Path("data/apps/eShopOnWeb/Catalog.zip")
CSV = Path("data/apps/eShopOnWeb/eShopOnContainers-sonarqube-quality-analysis.csv")
OUT = Path("output/paper_results/stats/oracle_validation.md")
EXTS = [".cs"]


def main() -> None:
    md = ["# Oracle validation — eShopOnContainers Catalog (RQ1/RQ2)\n",
          f"Archive `{ZIP}`, oracle `{CSV}`, extensions {EXTS}. Generated by `validate_oracle.py`.\n"]

    raw = _read_csv_robust(str(CSV))
    low = {c.lower(): c for c in raw.columns}
    ids = raw[low["id"]] if "id" in low else None
    key_cols = [low[c] for c in ("file", "rule", "startline", "endline", "startcolumn", "endcolumn") if c in low]
    dup = int(raw.duplicated(subset=key_cols).sum())
    md.append("## Oracle file\n")
    md.append(f"- records: {len(raw)}; unique ids: {ids.nunique() if ids is not None else 'n/a'}; "
              f"exact duplicate findings: {dup}")

    gt = load_ground_truth_spans(str(CSV), allowed_exts=EXTS)
    bad = gt[(gt["startLine"] < 1) | (gt["endLine"] < gt["startLine"])]
    md.append(f"- records for {EXTS} with a valid line: {len(gt)}; invalid ranges after loading: {len(bad)}\n")

    zdf = _zip_listing(str(ZIP), EXTS)
    md.append("## Archive\n")
    md.append(f"- {len(zdf)} files; duplicate file names inside the archive: "
              f"{int(zdf['basename'].duplicated().sum())}\n")

    old = gt[gt["basename"].isin(set(zdf["basename"]))]
    aligned, _, diag = _align_gt_to_zip(gt, zdf)
    md.append("## File-name vs path matching (whole archive)\n")
    md.append(f"- alignment: mode `{diag['mode']}`, archive prefix `{diag.get('zip_prefix')}` -> "
              f"oracle prefix `{diag.get('gt_prefix')}`")
    md.append(f"- spans matched by file name: {len(old)} on {old['basename'].nunique()} files")
    md.append(f"- spans matched by path: {len(aligned)} on {aligned['basename'].nunique()} files")
    md.append(f"- oracle records not in this archive (other services): {diag.get('gt_spans_dropped')}\n")

    md.append("| File (archive) | spans, file-name matching | spans, path matching | foreign spans |\n|---|---|---|---|")
    for base, grp in sorted(old.groupby("basename"), key=lambda kv: -len(kv[1])):
        own = aligned[aligned["basename"].str.endswith("/" + base)]
        if len(grp) != len(own):
            md.append(f"| {base} | {len(grp)} | {len(own)} | {len(grp) - len(own)} |")
    md.append("")

    universe, udiag, corrected = _build_universe(str(ZIP), gt, EXTS, 20, 1.0)
    al = udiag["gt_alignment"]
    md.append("## Line numbers\n")
    md.append("Share of single-line records whose column range falls on non-blank text when the "
              f"reported line is shifted by k ({al.get('checked')} records checked):\n")
    md.append("| k | " + " | ".join(al.get("fit_rate", {})) + " |\n|---|" + "---|" * len(al.get("fit_rate", {})))
    md.append("| fit | " + " | ".join(str(v) for v in al.get("fit_rate", {}).values()) + " |")
    md.append(f"\nApplied line offset: **{al.get('line_offset')}** (the export reports 0-based lines).\n")
    md.append("## RQ1/RQ2 universe (Top-k = 20, requested positive ratio 1.00)\n")
    md.append(f"- files with at least one oracle span in the archive: {udiag['mapped_gt_files']}; "
              f"selected positives: {udiag['positives']}; negatives: {udiag['negatives']} "
              f"(achieved positive ratio {udiag['positives'] / max(1, udiag['top_k_total_files']):.2f})")
    md.append(f"- oracle spans in the universe: {int(universe['gt_lines'].sum())}\n")

    md.append("## Manual inspection sample (10 random matched records after correction, seed 7)\n")
    md.append("| File | Lines | Rule | Source line |\n|---|---|---|---|")
    rule_col = low.get("rule")
    rules = dict(zip(raw[low["file"]].astype(str) + ":" + raw[low["startline"]].astype(str), raw[rule_col])) if rule_col else {}
    names = {n.lower(): n for n in zipfile.ZipFile(ZIP).namelist()}
    rng = random.Random(7)
    with zipfile.ZipFile(ZIP) as z:
        for _, r in corrected.sample(n=min(10, len(corrected)), random_state=rng.randint(0, 10**6)).iterrows():
            lines = z.read(names[r["basename"]]).decode("utf-8", "ignore").splitlines()
            src = lines[r["startLine"] - 1].strip().replace("|", "\\|")[:80] if r["startLine"] <= len(lines) else "(beyond end)"
            rule = rules.get(f"{r['file']}:{r['startLine'] - al.get('line_offset', 0)}", r.get("type"))
            md.append(f"| {r['basename']} | {r['startLine']}-{r['endLine']} | {rule} | `{src}` |")
    md.append("")

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(md))
    print(f"Wrote {OUT}")


if __name__ == "__main__":
    main()
